"""Write supabase/sample_leaderboard.sql: placeholder players for the leaderboard (tagged "sample" in the app).

Each made-up player is active in one to three neighborhoods (the leaderboard's areas, from supabase/leaderboard.sql),
with weekly <= monthly <= all-time points. The output is the same every run (fixed random seed).
Run:  python tools/make_sample_leaderboard.py
"""
import os, random, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sql = open(os.path.join(ROOT, "supabase", "leaderboard.sql"), encoding="utf-8").read()
block = sql[sql.index("insert into public.tf_areas"):]
AREAS = re.findall(r"\('([^']+)',\s*[\d.]+,\s*-[\d.]+\)", block[:block.index("on conflict")])

NAMES = ["Happy Hour Hero", "Pint Scout", "Tab Tracker", "Last Call Lou", "Draft Dodger", "Two Dollar Tuesday", "The Pour Report",
         "Cheap Seats", "Lager Logger", "Well Drink Wanda", "Shorty Seeker", "Tallboy Ted", "Muddy Regular", "Kendall Commuter",
         "Back Bay Bargains", "Fenway Frugal", "Southie Sipper", "Allston Ale Hunter", "Porter Sq Pints", "Inman Insider",
         "Beacon Hill Budget", "North End Nickel", "JP Penny Pincher", "Seaport Saver", "Charlestown Cheers", "Dot Draft Fan",
         "Roxbury Rounds", "Brighton Brew Boss", "Harvard Sq Happy Hour", "Central Sq Cents", "Eastie Elbow Bender",
         "Union Sq Undercut", "Cambridgeport Crawl", "Mission Hill Markdown", "Longwood Low Price", "West End Wallet"]

rnd = random.Random(2026)
rows = []
for name in NAMES:
    total = min(round(rnd.paretovariate(1.3) * 45 + rnd.uniform(5, 25), 1), 950.0)  # a few big players, a long tail
    home = [a for a in AREAS if a.lower().split()[0][:5] in name.lower()]  # "Kendall Commuter" lives in Kendall Sq
    n = rnd.choice([1, 2, 2, 3])
    picks = home[:1] + rnd.sample([a for a in AREAS if a not in home], n - len(home[:1]))
    weights = [rnd.uniform(1, 3) if i == 0 else rnd.uniform(0.3, 1.2) for i in range(len(picks))]
    for area, w in zip(picks, weights):
        all_time = round(total * w / sum(weights), 1)
        month = round(all_time * rnd.uniform(0.15, 0.55), 1)
        week = round(month * rnd.uniform(0.1, 0.5), 1)
        rows.append((name, area, week, month, all_time))

q = lambda s: "'" + s.replace("'", "''") + "'"
values = ",\n".join(f"  ({q(n)}, {q(a)}, {w}, {m}, {t})" for n, a, w, m, t in rows)
out = f"""-- TabFriendly: sample players for the leaderboard, so the boards aren't empty early on.
-- Run in the Supabase SQL Editor after leaderboard.sql (safe to re-run: it replaces the sample rows).
-- They show on the weekly, monthly and all-time boards (and neighborhood boards) tagged "sample" in the app.
-- They aren't accounts: no prices, no votes, never bar mayors, and they don't change anyone's points.
-- Generated by tools/make_sample_leaderboard.py. To remove them all:
--   delete from public.tf_sample_scores where true;

delete from public.tf_sample_scores where true;
insert into public.tf_sample_scores (name, area, week, month, all_time) values
{values};
"""
path = os.path.join(ROOT, "supabase", "sample_leaderboard.sql")
open(path, "w", encoding="utf-8", newline="\n").write(out)
print(f"{len(NAMES)} sample players, {len(rows)} rows in {len({r[1] for r in rows})} of {len(AREAS)} neighborhoods -> {path}")
